"""Writes RESULTS.md from results/summary.json. Every number is filled in from the data.

    python evaluation/report.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
S = json.loads((HERE / "results" / "summary.json").read_text())
SCALE = 10


def f(x, d=1, unit=""):
    return "–" if x is None else f"{x:.{d}f}{unit}"


def mr(r, d=1, unit="", scale=1.0):
    """mean (min–max) over repeats"""
    if not r:
        return "–"
    if r["n"] == 1 or r["min"] == r["max"]:
        return f(r["mean"] * scale, d, unit)
    return f"{f(r['mean'] * scale, d, unit)} ({f(r['min'] * scale, d)}–{f(r['max'] * scale, d)})"


def run(name):
    return S["runs"].get(name)


out = []
w = out.append

w("# Evaluation results\n")
w("Generated by `evaluation/report.py` from the raw runs in `results/`; see [README.md](README.md) "
  "for how the experiments work and how to rerun them. Times from scaled runs are converted back "
  f"to real-world seconds (×{SCALE}). Every run's server logs were checked for unexpected exceptions: "
  f"{'none found' if not any(S.get('serverErrors', {}).values()) else 'SEE serverErrors'}. "
  "Environment: one Linux machine with 2 CPU cores; AWS (DynamoDB, SQS) emulated with moto 5.2, "
  "Redis 7.0, Python 3.13, Node.js 22.\n")

# ------------------------------------------------------------------ headline
def runs_like(prefix):
    return [r for n, r in S["runs"].items() if n.startswith(prefix)]


w("## Headline\n")
ob = [r for n, r in S["runs"].items() if n.startswith("E1-") and "-outbox-r" in n]
if ob:
    made, lost = sum(r["made_by_live_phones"] for r in ob), sum(r["lost"] for r in ob)
    waiting = sum(r["still_on_phone_at_end"] for r in ob)
    dup = sum(r["queue_extra_copies"] for r in ob)
    order = sum(r["trips_out_of_order"] for r in ob)
    w(f"- **No check-in lost by the CareRoute app**: {lost} of {made:,} lost across {len(ob)} signal-loss runs "
      f"(1, 5 and 10 minutes), {waiting} still waiting on a phone at the end, {dup} extra queue copies, "
      f"{order} trips out of order.")
nv = S["E1"].get("5min-naive")
if nv:
    w(f"- An app that sends each check-in once lost {f(nv['lost_pct']['mean'], 0, '%')} of them in a 5-minute outage.")
rs = [run("E1-restart-indexeddb"), run("E1-restart-memory")]
if all(rs):
    w(f"- App closed and reopened mid-outage: {rs[0]['lost']} lost with the outbox in IndexedDB, "
      f"{rs[1]['lost']} of {rs[1]['made']:,} ({f(rs[1]['lost_pct'], 0, '%')}) if it were kept in memory.")
b2 = [run("E1-batch-budget-off"), run("E1-batch-budget-on")]
if all(b2):
    pcts = [100 * (r["made"] - r["still_on_phone_at_end"] - r["lost"]) / r["made"] for r in b2]
    w(f"- **Retry storm found and fixed**: after a 5-minute outage, with no time limit on batches only "
      f"{f(pcts[0], 0, '%')} of check-ins were acknowledged to the phones by the end, although the server had stored "
      f"{f(100 * b2[0]['stored'] / b2[0]['made'], 0, '%')}; with the 1 s limit, {f(pcts[1], 0, '%')}.")
e2 = S.get("E2") or {}
if e2.get("lockstep") and e2.get("full"):
    lk, fu = e2["lockstep"], e2["full"]
    window = len(lk["delivered_pct"]) * lk["bin_s"]
    w(f"- {fu['phones']} phones reconnecting at once to an overloaded server: with no randomness only "
      f"{f(lk['delivered_pct_end'], 0, '%')} of the backlog got through in {f(window, 0, ' s')}; with random retry "
      f"delays and a spread reconnect, all of it in {f(fu['seconds_to_deliver_all'], 0, ' s')}, and the peak load fell from "
      f"{f(lk['peak_offered_per_s'], 0)} to {f(fu['peak_offered_per_s'], 0)} requests/s.")
e3 = S.get("E3") or {}
if e3.get("off") and e3.get("on"):
    k = e3.get("on-leader-killed") or {}
    tk = f"; with the leader replica killed, another took over after {f(k['takeover_s'] * SCALE, 0, ' s')} and {k['stuck_end']} were left" if k.get("takeover_s") is not None else ""
    w(f"- Server failing part-way, 30% of phones dying: without the clean-up task {e3['off']['stuck_end']} check-ins "
      f"stayed stuck for good; with it, {e3['on']['stuck_end']}{tk}.")
e4 = S.get("E4")
if e4 and e4.get("detect_s_design") and e4.get("detect_s_naive"):
    w(f"- Heartbeat rule: a phone that dies right after catching up is suspected after "
      f"{f(e4['detect_s_design']['median'], 0, ' s')} (median) with single live check-ins only, against "
      f"{f(e4['detect_s_naive']['median'], 0, ' s')} if every arrival counted.")
w("")

# ------------------------------------------------------------------ E1
w("## E1: signal loss (20 phones, 3 runs each)\n")
w("| Outage | App | Check-ins lost | Extra queue copies | Trips out of order | Stuck on server | Left on phone | "
  "Delay of check-ins made offline, median / max | Requests per check-in |")
w("|---|---|---|---|---|---|---|---|---|")
for key in sorted(S["E1"], key=lambda k: (int(k.split("min")[0]), k.split("-")[1] != "outbox")):
    r = S["E1"][key]
    minutes, kind = key.split("-")
    app = "CareRoute (outbox)" if kind == "outbox" else "send once"
    delay = "–" if kind == "naive" else f"{mr(r['delay_s_outage_p50'], 0, ' s', SCALE)} / {mr(r['delay_s_outage_max'], 0, ' s', SCALE)}"
    w(f"| {minutes.replace('min', ' min')} | {app} | {mr(r['lost_pct'], 1, '%')} | {mr(r['queue_extra_copies_pct'], 1, '%')} | "
      f"{mr(r['trips_out_of_order'], 0)} | {mr(r['stuck_on_server'], 0)} | {mr(r['still_on_phone_at_end'], 0)} | {delay} | "
      f"{mr(r['requests_per_checkin'], 2)} |")
w("\nThe delay column is measured from when the check-in was made, so it includes the outage itself. "
  "After the signal returned, the scaled runs took longer to catch up than real time would: the 1:10 clock "
  "also makes the catch-up load 10 times heavier for the local emulator. The full-length run below is the "
  "realistic catch-up figure.")
w("\n![E1](figures/e1-loss.png)\n")

real = run("E1-real-5min-outbox")
if real:
    w("**Full-length check (E1-real, no time scaling, 50 phones, 10 s heartbeat, 5-minute outage):** "
      f"{real['made']} check-ins made, {real['lost']} lost, {real['stuck_on_server']} stuck, "
      f"{real['still_on_phone_at_end']} left on phones, {real['trips_out_of_order']} trips out of order, "
      f"{f(real['queue_extra_copies_pct'], 1, '%')} extra queue copies. Check-ins made offline reached the server a median "
      f"{f(real['catchup_s_p50'], 0, ' s')} after the signal returned (max {f(real['catchup_s_max'], 0, ' s')}): the random "
      f"backoff the phone was in when the signal came back, then one batch.\n")

rs = [run("E1-restart-indexeddb"), run("E1-restart-memory")]
if all(rs):
    w("**App closed and reopened in the middle of a 5-minute outage:**\n")
    w("| Outbox kept in | Check-ins lost |")
    w("|---|---|")
    for label, r in zip(("IndexedDB (the app)", "memory only"), rs):
        w(f"| {label} | {r['lost']} of {r['made']} ({f(r['lost_pct'], 1, '%')}) |")
    w("")

b = [run("E1-batch-budget-off"), run("E1-batch-budget-on")]
if all(b):
    w("## E1-budget: the retry storm found during this evaluation\n")
    w("| Server batch time limit | Stored and queued on the server | Acknowledged to the phone by the end | Left on phones | Extra queue copies | Requests |")
    w("|---|---|---|---|---|---|")
    for label, r in zip(("none", "1 s (current design)"), b):
        acked = r["made"] - r["still_on_phone_at_end"] - r["lost"]
        w(f"| {label} | {f(100 * r['queued_unique'] / r['made'], 0, '%')} | {f(100 * acked / r['made'], 0, '%')} | "
          f"{r['still_on_phone_at_end']} | {r['queue_extra_copies']} | {r['requests']} |")
    w("\nWithout a limit the server did store and queue every check-in, but each big catch-up batch took longer "
      "than the phone's timeout, so the phone gave up, resent the same batch (making duplicate work and extra queue "
      "copies), and never heard back: a retry storm that keeps itself going. With the limit every answer comes within about a second and says how many it "
      "handled (`processed`).")
    w("\n![E1-budget](figures/e1-retry-storm.png)\n")

# ------------------------------------------------------------------ E2
if S.get("E2"):
    any_v = next(iter(S["E2"].values()))
    w(f"## E2: {any_v['phones']} phones regain signal at once ({any_v['backlog_per_phone']} check-ins of backlog each, "
      "server capacity fixed at 4 requests at once)\n")
    w("| Phones' behaviour | Backlog delivered | Time to deliver 95% / all | Requests | Turned away (503) | Peak load |")
    w("|---|---|---|---|---|---|")
    for key, label in (("lockstep", "no randomness"), ("jitter-retries", "random retry delays"),
                       ("full", "random retry delays + spread reconnect (CareRoute)")):
        v = S["E2"].get(key)
        if v:
            w(f"| {label} | {f(v['delivered_pct_end'], 0, '%')} | {f(v['seconds_to_deliver_95'], 0, ' s')} / "
              f"{f(v['seconds_to_deliver_all'], 0, ' s') if v['all_delivered'] else 'not within ' + f(len(v['delivered_pct']) * v['bin_s'], 0, ' s')} | "
              f"{v['requests_after_reconnect']} | {v['shed_after_reconnect']} | {f(v['peak_offered_per_s'], 0, ' req/s')} |")
    w("\n![E2](figures/e2-reconnect-storm.png)\n")

# ------------------------------------------------------------------ E3
if S.get("E3"):
    w("## E3: server fails part-way, phones die (2 replicas, 20% of queue sends fail after storing, "
      "30% of phones die at their first failure)\n")
    w("| Clean-up task | Stuck at peak | Stuck at the end | Leader takeover after a crash |")
    w("|---|---|---|---|")
    for key, label in (("off", "off"), ("on", "on"), ("on-leader-killed", "on, leader replica killed")):
        v = S["E3"].get(key)
        if v:
            w(f"| {label} | {v['stuck_peak']} | {v['stuck_end']} | "
              f"{f(v['takeover_s'] * SCALE, 0, ' s (lease 30 s)') if v['takeover_s'] is not None else '–'} |")
    w("")
    for key, label in (("off", "Clean-up off"), ("on", "Clean-up on"), ("on-leader-killed", "Leader killed")):
        r = run(f"E3-cleanup-{key}")
        if r:
            w(f"- {label}: {r['made']} check-ins made (all stored), {r['queued_unique']} reached the queue, "
              f"{r['stuck_on_server']} stuck; {r['lost']} lost from phones that stayed alive.")
    w("\nThe stuck count goes up and down during a run because a check-in is briefly \"stuck\" between being stored "
      "and being queued, and a failed queue send leaves it so until the phone retries or the clean-up task "
      "(after 30 s) finishes it. What matters is the end: only check-ins from phones that died stay stuck, "
      "and only without the clean-up task.")
    w("\n![E3](figures/e3-cleanup.png)\n")

# ------------------------------------------------------------------ E4
e4 = S.get("E4")
if e4:
    w("## E4: noticing a phone that dies right after catching up\n")
    w(f"Phi accrual failure detector (Hayashibara et al., normal model, threshold φ = {e4['threshold']:g}, "
      f"minimum spread {e4['min_std_s']} s, last {e4['window']} intervals), applied to the interval history of "
      f"each of the {e4['phones']} phones in E1-real after the 5-minute outage.\n")
    w("| Interval history | Time to suspect a dead phone (median, min–max) |")
    w("|---|---|")
    for key, label in (("detect_s_before_outage", "normal rhythm, before the outage"),
                       ("detect_s_design", "after the outage, CareRoute rule (single live check-ins only)"),
                       ("detect_s_naive", "after the outage, if every arrival counted (batches too)")):
        v = e4.get(key)
        if v:
            w(f"| {label} | {f(v['median'], 1, ' s')} ({f(v['min'], 1)}–{f(v['max'], 1)}) |")
    w(f"\nWith every arrival counted, the window holds a median of {e4['zero_gaps_naive_median']:.0f} zero-length "
      "gaps from the catch-up batch plus the outage gap itself.\n")
    w("![E4](figures/e4-heartbeat.png)\n")

(HERE / "RESULTS.md").write_text("\n".join(out))
print("wrote evaluation/RESULTS.md")
